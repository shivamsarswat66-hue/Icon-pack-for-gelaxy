#!/usr/bin/env node
/**
 * CineMatch static build for Vercel / GitHub Pages / Netlify.
 *
 * The Node app (server.js) is the "full" edition: real HTTP API + JSON file store.
 * This build ships the exact same engine to the browser so the site runs with no
 * server at all — profiles persist in localStorage. Vercel's filesystem is
 * ephemeral, so this is the edition that belongs there.
 *
 *   node build.js   ->  dist/
 */
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const DIST = path.join(ROOT, "dist");

const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
const write = (p, s) => {
  const target = path.join(DIST, p);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, s);
};

function bundle() {
  // ---- data/movies.js -> window.CineData -------------------------------------
  // the imported catalogue first: data/movies.js pulls it in via require(), which
  // doesn't exist in a browser, so it is published as window.CineExtra instead.
  let extra = "window.CineExtra = [];";
  try {
    extra = read("data/movies.extra.js").replace(/module\.exports\s*=\s*/, "window.CineExtra = ");
  } catch (_) {
    console.warn("  · no data/movies.extra.js — building with the curated catalogue only");
  }

  let data = read("data/movies.js")
    .replace(/module\.exports\s*=\s*\{[^}]*\};?/, "window.CineData = { movies, byId, ALL_GENRES, ALL_INDUSTRIES, INDUSTRIES, slugify };")
    .replace(/require\(\s*["']\.\/movies\.extra["']\s*\)/, "window.CineExtra");
  if (!data.includes("window.CineData"))
    throw new Error("data/movies.js: could not find module.exports to convert");

  // ---- src/engine.js -> window.CineEngine ------------------------------------
  let engine = read("src/engine.js")
    .replace(
      /const\s*\{\s*movies,\s*byId,\s*ALL_GENRES,\s*INDUSTRIES\s*\}\s*=\s*require\(["'][^"']+["']\);/,
      "const { movies, byId, ALL_GENRES, INDUSTRIES } = window.CineData;"
    )
    .replace(/module\.exports\s*=\s*\{/, "window.CineEngine = {");
  if (!engine.includes("window.CineEngine"))
    throw new Error("src/engine.js: could not find module.exports to convert");
  if (engine.includes("require("))
    throw new Error("src/engine.js: a require() survived the transform");

  // browser build of the online lookup: no module.exports, so it self-installs as window.CineLookup
  const lookupSrc = read("src/lookup.js");

  return [
    "/* CineMatch — generated by build.js. Do not edit; edit data/movies.js + src/engine.js + src/lookup.js */",
    "(function () {",
    '"use strict";',
    extra,
    "})();",
    "(function () {",
    '"use strict";',
    data,
    "})();",
    "(function () {",
    '"use strict";',
    engine,
    "})();",
    lookupSrc,
    "",
  ].join("\n");
}

function main() {
  fs.rmSync(DIST, { recursive: true, force: true });

  write("engine.bundle.js", bundle());
  write("local-api.js", read("src/localapi.js"));
  write("app.js", read("public/app.js"));
  write("styles.css", read("public/styles.css"));

  let html = read("public/index.html");
  const inject =
    '<script src="engine.bundle.js"></script>\n    <script src="local-api.js"></script>\n    <script src="app.js"></script>';
  if (!html.includes('<script src="app.js"></script>'))
    throw new Error("public/index.html: app.js script tag not found");
  html = html.replace('<script src="app.js"></script>', inject);
  write("index.html", html);

  // 404 -> SPA shell (harmless: the app is a single screen)
  write("404.html", html);

  const files = ["index.html", "404.html", "styles.css", "app.js", "local-api.js", "engine.bundle.js"];
  const kb = (f) => (fs.statSync(path.join(DIST, f)).size / 1024).toFixed(1) + " KB";
  console.log("dist/ built:");
  for (const f of files) console.log("  " + f.padEnd(20) + kb(f));
}

main();
