#!/usr/bin/env node
/**
 * Post-pass over data/movies.extra.js — no network calls.
 *  · strips genres that leaked in from the film's own title ("Civil War" → War)
 *  · maps regional Indian films out of "Bollywood" using their language
 *  · rewrites the machine-composed synopses into readable sentences
 *  · drops meaningless keywords ("language")
 */
const fs = require("fs");
const path = require("path");
const lookup = require("../src/lookup");
const { movies: core, byId, ALL_GENRES, INDUSTRIES } = require("../data/movies");
lookup.init({ movies: core, byId, genres: ALL_GENRES, industries: INDUSTRIES });

const FILE = path.join(__dirname, "..", "data", "movies.extra.js");
const films = require(FILE);
const REGIONAL = /tamil|telugu|malayalam|kannada|marathi|bengali|punjabi|gujarati|odia|assamese/i;
const titleGenres = (title) => lookup.genresFromExtract(`${title} is a film`);

let fixedGenres = 0, fixedIndustry = 0, fixedSynopsis = 0, dropped = 0;

const out = films.map((m) => {
  let genres = m.genres.slice();

  // 1 — remove a genre that is only justified by a word inside the title
  const fromTitle = titleGenres(m.title);
  const justified = lookup.genresFromExtract(m.synopsis);
  if (fromTitle.length) {
    const cleaned = genres.filter((g) => !(fromTitle.includes(g) && !justified.includes(g)));
    if (cleaned.length && cleaned.length !== genres.length) {
      genres = cleaned;
      fixedGenres++;
    }
  }
  // top up from the synopsis clause when we have room
  for (const g of justified) {
    if (genres.length >= 3) break;
    if (!genres.includes(g)) genres.push(g);
  }

  // 2 — regional Indian cinema is not Bollywood
  const syn = m.synopsis.toLowerCase();
  const langMatch = ["hindi", "tamil", "telugu", "malayalam", "kannada", "marathi", "bengali", "punjabi", "gujarati"].find((l) =>
    new RegExp(`\\b${l}(-language| language)`).test(syn)
  );
  let industry = m.industry;
  if (langMatch && langMatch !== "hindi" && REGIONAL.test(langMatch)) industry = "IN";
  else if (langMatch === "hindi") industry = "BW";
  if (industry !== m.industry) fixedIndustry++;

  // 3 — readable composed synopsis
  let synopsis = m.synopsis;
  if (/^\d{4}\s/.test(synopsis) || /\b(null|undefined)\b/.test(synopsis)) {
    const bits = [];
    const lang = langMatch ? `${langMatch[0].toUpperCase()}${langMatch.slice(1)}` : "";
    const name = INDUSTRIES[industry] || "World";
    bits.push(`A ${m.year} ${lang ? lang + "-language " : ""}${genres[0].toLowerCase()} film from ${name}`);
    if (m.director) bits.push(`directed by ${m.director}`);
    if (m.runtime) bits.push(`${m.runtime} minutes long`);
    synopsis = bits.join(", ") + ".";
    fixedSynopsis++;
  }

  // 4 — meaningless keywords
  const keywords = (m.keywords || []).filter((k) => k !== "language" && k !== "love" && k.length > 2);
  if (keywords.length !== (m.keywords || []).length) dropped++;

  if (!genres.length) return null; // would be inert
  return {
    ...m,
    industry,
    industryName: INDUSTRIES[industry] || "World Cinema",
    genres: genres.slice(0, 3),
    keywords: keywords.slice(0, 6),
    synopsis,
  };
}).filter(Boolean);

const header = `/**
 * AUTO-GENERATED by tools/import-wikidata.js (+ tools/refine-extra.js) — do not edit by hand.
 * ${out.length} films from Wikidata/Wikipedia. No ratings: none can be derived from
 * open data, and the ranker treats a missing rating as neutral rather than inventing one.
 */
module.exports = ${JSON.stringify(out, null, 0)};
`;
fs.writeFileSync(FILE, header);
const mix = out.reduce((a, m) => ((a[m.industry] = (a[m.industry] || 0) + 1), a), {});
console.log(`refined ${out.length} films`);
console.log(`  genres fixed: ${fixedGenres} | industry fixed: ${fixedIndustry} | synopses rewritten: ${fixedSynopsis} | keyword cleanup: ${dropped}`);
console.log("  industries:", Object.entries(mix).map(([k, v]) => `${INDUSTRIES[k] || k}=${v}`).join("  "));
